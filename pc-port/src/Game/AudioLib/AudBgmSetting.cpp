const u8* AudBgmSetting::getMuteState(JAISoundID soundID, s32 state) {
    s32 tableIndex = cBgmSettingInfo[soundID.getWaveID()].mMuteStateIndex;
    if (tableIndex < 0) {
        return nullptr;
    }

    return cMuteStateTable[tableIndex][state];
}

u16 AudBgmSetting::getExtraChordNum(JAISoundID soundID, s32 state) {
    s32 tableIndex = cBgmSettingInfo[soundID.getWaveID()].mExtraChordIndex;
    if (tableIndex < 0) {
        return 0xFFFF;
    }

    return cExtraChordNum[tableIndex][state];
}

